"""Check the simplified real-image reveal slider and optional controls."""
import os,re
from pathlib import Path
from playwright.sync_api import sync_playwright,expect

with sync_playwright() as p:
    browser=p.chromium.launch(headless=True,executable_path=os.environ.get('PLAYWRIGHT_CHROMIUM_EXECUTABLE'))
    page=browser.new_page(viewport={'width':1440,'height':1050});errors=[]
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.goto('http://127.0.0.1:3001',wait_until='networkidle',timeout=90000)
    expect(page.get_by_role('img',name='Signed difference image',exact=True)).to_be_visible(timeout=60000)
    expect(page.locator('.simple-processed')).to_contain_text('ZODI subtracted',timeout=60000)
    expect(page.get_by_role('button',name='Side by side',exact=True)).to_have_attribute('aria-pressed','true')
    date_slider=page.get_by_role('slider',name='Current observation slider',exact=True)
    expect(date_slider).to_be_visible()
    if date_slider.is_enabled():
        reference_date=page.locator('.simple-image-caption>span').first.inner_text()
        current_date=page.locator('.current-date-control strong').inner_text()
        target='0' if date_slider.input_value()!='0' else date_slider.get_attribute('max')
        with page.expect_response(lambda r:r.url.endswith('/analysis'),timeout=60000) as response:
            date_slider.fill(target)
        assert response.value.ok,response.value.text()
        expect(page.locator('.simple-image-caption>span').first).to_have_text(reference_date)
        expect(page.locator('.current-date-control strong')).not_to_have_text(current_date)
    page.get_by_role('checkbox',name='Mark changes on images',exact=True).check()
    expect(page.locator('.simple-difference')).to_be_hidden()
    expect(page.locator('.residual-results>summary')).to_have_text(re.compile(r'Highlighted changes \(\d+\)'),timeout=60000)
    count=page.locator('.residual-list>button').count()
    expect(page.locator('.simple-observations .residual-marker')).to_have_count(count*2,timeout=30000)
    if count:
        page.locator('.simple-observations .residual-marker').first.click(force=True)
        expect(page.locator('.simple-pick-position')).to_be_visible()
        expect(page.locator('.simple-inspector')).to_contain_text('Approx. significance')
    page.get_by_role('button',name='Before / after',exact=True).click()
    expect(page.locator('.comparison-markers .residual-marker')).to_have_count(count)
    page.get_by_role('checkbox',name='Mark changes on images',exact=True).uncheck()
    expect(page.get_by_role('img',name='Signed difference image',exact=True)).to_be_visible()
    slider=page.get_by_role('slider',name='Before and after slider',exact=True)
    expect(slider).to_be_enabled();expect(slider).to_have_value('50')
    assert not page.locator('.simple-extra').evaluate('(e)=>e.open')
    assert not page.locator('.comparison-options').evaluate('(e)=>e.open')
    assert not page.locator('.auto-pipeline').evaluate('(e)=>e.open')
    slider.fill('0');assert '100%' in page.locator('.swipe-before').evaluate('(e)=>e.style.clipPath')
    slider.press('ArrowRight');expect(slider).to_have_value('1')
    slider.press('End');expect(slider).to_have_value('100')
    assert '0%' in page.locator('.swipe-before').evaluate('(e)=>e.style.clipPath')
    slider.fill('50')
    handle=page.get_by_role('button',name='Drag image comparison divider')
    box=handle.bounding_box();surface=page.locator('.swipe-images').bounding_box()
    page.mouse.move(box['x']+box['width']/2,box['y']+box['height']/2);page.mouse.down()
    page.mouse.move(surface['x']+surface['width']*.75,box['y']+box['height']/2,steps=6);page.mouse.up()
    assert 73<=int(slider.input_value())<=77
    slider.fill('50')
    current=page.get_by_role('img',name='Current sky observation',exact=True)
    box=current.bounding_box();current.click(position={'x':box['width']*.75,'y':box['height']*.5})
    expect(page.locator('.simple-pick-position')).to_be_visible()
    page.get_by_role('button',name='Significance',exact=True).click()
    expect(page.get_by_role('img',name='Approximate significance image',exact=True)).to_be_visible()
    page.get_by_role('button',name='Difference',exact=True).click()
    page.get_by_text('More options',exact=True).click()
    expect(page.get_by_role('checkbox',name='Subtract zodiacal light (ZODI)',exact=True)).to_be_checked()
    page.get_by_text('More options',exact=True).click()
    output=Path('test-results');output.mkdir(exist_ok=True)
    page.wait_for_load_state('networkidle');page.evaluate('window.scrollTo(0,0)');page.screenshot(path=str(output/'simple-slider-desktop.png'),full_page=True)
    page.set_viewport_size({'width':390,'height':844});page.wait_for_load_state('networkidle')
    slider.fill('25');expect(slider).to_have_value('25')
    assert not page.evaluate('document.documentElement.scrollWidth>innerWidth')
    page.evaluate('window.scrollTo(0,0)');page.screenshot(path=str(output/'simple-slider-mobile.png'),full_page=True)
    assert not errors,errors
    browser.close()
    print('Passed both comparison layouts, current-date slider with fixed reference, inline change markers, reveal dragging/keyboard control, pixel inspection, ZODI default and mobile layout.')
